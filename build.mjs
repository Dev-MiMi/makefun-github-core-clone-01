// Babel is a local build tool; the generated forge imports only Node libraries.
import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const require = createRequire(import.meta.url);
const expected = {'@babel/core': '7.20.12', '@babel/plugin-transform-typescript': '7.20.13'};
for (const [name, version] of Object.entries(expected)) {
  let installed;
  try { installed = require(`${name}/package.json`).version; }
  catch { throw new Error(`Build requires locally available ${name}@${version}; no installation runs automatically.`); }
  if (installed !== version) throw new Error(`Build requires ${name}@${version}, found ${installed}.`);
}
const babel = require('@babel/core');
const typescript = require('@babel/plugin-transform-typescript');
const args = process.argv.slice(2);
if (args.length > 1 || args.some(arg => arg !== '--check')) throw new Error('Usage: node build.mjs [--check]');
const check = args.includes('--check');
const names = ['domain', 'git', 'graphql', 'api', 'server'];
const outputs = names.map(name => {
  const source = readFileSync(new URL(`${name}.ts`, import.meta.url), 'utf8');
  let code = babel.transformSync(source, {
    filename: fileURLToPath(new URL(`${name}.ts`, import.meta.url)),
    configFile: false,
    babelrc: false,
    plugins: [typescript],
    comments: true,
    compact: false
  }).code;
  for (const dependency of names) code = code.replaceAll(`'./${dependency}.ts'`, `'./${dependency}.mjs'`);
  return {name: `${name}.mjs`, bytes: Buffer.from(code + '\n')};
});
let drift = false;
for (const {name, bytes} of outputs) {
  const path = new URL(name, import.meta.url);
  let current;
  try { current = readFileSync(path); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (current?.equals(bytes)) continue;
  if (check) {
    console.error(`Runtime drift: ${name}; regenerate with node build.mjs.`);
    drift = true;
  } else {
    writeFileSync(path, bytes);
    console.log(`Built ${name}`);
  }
}
if (drift) process.exitCode = 1;
else console.log(check ? 'All five runtime modules match generated bytes.' : 'Runtime build complete.');
